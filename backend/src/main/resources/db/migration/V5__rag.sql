CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE rag_embedding (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id bigint NOT NULL REFERENCES benefit(id) ON DELETE CASCADE,
    chunk_no integer NOT NULL,
    content text NOT NULL,
    verified_hash char(64) NOT NULL,
    model varchar(100) NOT NULL,
    embedding vector(1536) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (benefit_id, chunk_no, verified_hash, model)
);
CREATE INDEX ix_rag_embedding_benefit ON rag_embedding(benefit_id);
