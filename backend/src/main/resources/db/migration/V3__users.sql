CREATE TABLE user_account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(320),
    display_name varchar(100) NOT NULL,
    role varchar(10) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE social_account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    provider varchar(10) NOT NULL CHECK (provider IN ('GOOGLE', 'KAKAO', 'DEV')),
    provider_user_id varchar(255) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, provider_user_id)
);
CREATE INDEX ix_social_account_user ON social_account(user_id);

CREATE TABLE parent_profile (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    age smallint NOT NULL CHECK (age BETWEEN 0 AND 120),
    ctpv_name varchar(50) NOT NULL,
    sgg_name varchar(50),
    ltc_grade smallint CHECK (ltc_grade BETWEEN 1 AND 6),
    has_no_ltc_grade boolean,
    income_median_pct smallint CHECK (income_median_pct BETWEEN 0 AND 1000),
    basic_livelihood boolean,
    near_poverty boolean,
    basic_pension boolean,
    disability boolean,
    veteran boolean,
    living_alone boolean,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (ltc_grade IS NULL OR has_no_ltc_grade IS DISTINCT FROM true)
);
CREATE INDEX ix_parent_profile_user ON parent_profile(user_id);

CREATE TABLE saved_benefit (
    user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    benefit_id bigint NOT NULL REFERENCES benefit(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, benefit_id)
);
