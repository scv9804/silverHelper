CREATE TABLE notification_setting (
    user_id bigint PRIMARY KEY REFERENCES user_account(id) ON DELETE CASCADE,
    email_enabled boolean NOT NULL DEFAULT false,
    new_benefit_enabled boolean NOT NULL DEFAULT true,
    deadline_enabled boolean NOT NULL DEFAULT true,
    deadline_days smallint NOT NULL DEFAULT 7 CHECK (deadline_days BETWEEN 1 AND 30),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE notification_delivery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    profile_id bigint NOT NULL REFERENCES parent_profile(id) ON DELETE CASCADE,
    benefit_id bigint NOT NULL REFERENCES benefit(id) ON DELETE CASCADE,
    kind varchar(20) NOT NULL CHECK (kind IN ('NEW_BENEFIT', 'DEADLINE')),
    event_key varchar(100) NOT NULL,
    status varchar(10) NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now(),
    sent_at timestamptz,
    UNIQUE (user_id, profile_id, benefit_id, kind, event_key)
);
CREATE INDEX ix_notification_delivery_retry ON notification_delivery(status, created_at);
