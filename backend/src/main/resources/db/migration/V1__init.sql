-- V1: 혜택 수집·AI 추출·검토 대기열 기본 스키마
-- 설계 근거: docs/adr/0002-db-schema.md, docs/specs/public-api.md

-- 같은 사업을 원천 간에 묶는 그룹 (ADR 0002 §3)
CREATE TABLE benefit_group (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primary_benefit_id bigint,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);

-- 원천별 혜택 1건
CREATE TABLE benefit (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source               varchar(20)  NOT NULL,
    source_id            varchar(100) NOT NULL,
    group_id             bigint       NOT NULL REFERENCES benefit_group (id),
    name                 varchar(300) NOT NULL,
    summary              text,
    source_url           varchar(1000) NOT NULL,
    agency_name          varchar(200),
    department_name      varchar(200),
    ctpv_name            varchar(50),
    sgg_name             varchar(50),
    support_cycle        varchar(100),
    provision_type       varchar(100),
    apply_method_name    varchar(200),
    online_apply         boolean,
    contact              varchar(500),
    base_year            smallint,
    enforce_start_date   date,
    enforce_end_date     date,
    source_registered_on date,
    source_modified_at   timestamptz,
    content_hash         char(64)     NOT NULL,
    verified_hash        char(64),
    status               varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    first_collected_at   timestamptz  NOT NULL,
    last_collected_at    timestamptz  NOT NULL,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_benefit_source UNIQUE (source, source_id),
    CONSTRAINT ck_benefit_source CHECK (source IN ('NATIONAL', 'LOCAL', 'GOV24')),
    CONSTRAINT ck_benefit_status CHECK (status IN ('ACTIVE', 'ENDED', 'REMOVED'))
);

CREATE INDEX ix_benefit_group ON benefit (group_id);
CREATE INDEX ix_benefit_visible ON benefit (status) WHERE verified_hash IS NOT NULL;
CREATE INDEX ix_benefit_region ON benefit (ctpv_name, sgg_name);

ALTER TABLE benefit_group
    ADD CONSTRAINT fk_benefit_group_primary FOREIGN KEY (primary_benefit_id) REFERENCES benefit (id);

-- 원문 응답 (해시가 다른 버전마다 1행)
CREATE TABLE benefit_raw (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id    bigint      NOT NULL REFERENCES benefit (id),
    kind          varchar(20) NOT NULL,
    content_hash  char(64)    NOT NULL,
    payload       jsonb       NOT NULL,
    raw_body      text        NOT NULL,
    first_seen_at timestamptz NOT NULL,
    last_seen_at  timestamptz NOT NULL,
    CONSTRAINT uk_benefit_raw UNIQUE (benefit_id, kind, content_hash),
    CONSTRAINT ck_benefit_raw_kind CHECK (kind IN ('LIST', 'DETAIL', 'CONDITIONS'))
);

-- 원천 코드 태그: 생애주기, 가구유형, 관심주제 (public-api.md §5)
CREATE TABLE benefit_tag (
    benefit_id bigint      NOT NULL REFERENCES benefit (id) ON DELETE CASCADE,
    tag_type   varchar(20) NOT NULL,
    code       varchar(10) NOT NULL,
    PRIMARY KEY (benefit_id, tag_type, code),
    CONSTRAINT ck_benefit_tag_type CHECK (tag_type IN ('LIFE', 'HOUSEHOLD', 'THEME'))
);

CREATE INDEX ix_benefit_tag_code ON benefit_tag (tag_type, code);

-- 문의처, 관련 사이트, 근거법령, 서식, 신청 절차
CREATE TABLE benefit_reference (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id bigint      NOT NULL REFERENCES benefit (id) ON DELETE CASCADE,
    ref_type   varchar(20) NOT NULL,
    name       varchar(500),
    value      text,
    sort_order int         NOT NULL DEFAULT 0,
    CONSTRAINT ck_benefit_reference_type CHECK (ref_type IN ('CONTACT', 'SITE', 'LAW', 'FORM', 'APPLY'))
);

CREATE INDEX ix_benefit_reference_benefit ON benefit_reference (benefit_id);

-- AI 추출 결과 원본 (원문 버전 × 모델 × 프롬프트 버전마다 1행)
CREATE TABLE ai_extraction (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id     bigint       NOT NULL REFERENCES benefit (id),
    raw_id         bigint       NOT NULL REFERENCES benefit_raw (id),
    provider       varchar(20)  NOT NULL,
    model          varchar(100) NOT NULL,
    prompt_version varchar(50)  NOT NULL,
    result         jsonb,
    schema_valid   boolean      NOT NULL,
    error_message  text,
    input_tokens   int,
    output_tokens  int,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_ai_extraction UNIQUE (raw_id, provider, prompt_version),
    CONSTRAINT ck_ai_extraction_provider CHECK (provider IN ('CLAUDE', 'GPT'))
);

CREATE INDEX ix_ai_extraction_benefit ON ai_extraction (benefit_id);

-- 확정된 자격 조건 (혜택당 1행). NULL = 조건 없음 또는 원문에 언급 없음 (ADR 0002 §6)
CREATE TABLE benefit_eligibility (
    benefit_id               bigint PRIMARY KEY REFERENCES benefit (id) ON DELETE CASCADE,
    extraction_id            bigint      NOT NULL REFERENCES ai_extraction (id),
    min_age                  smallint,
    max_age                  smallint,
    ltc_required             boolean,
    ltc_grades               smallint[],
    income_max_median_pct    smallint,
    requires_basic_livelihood boolean,
    requires_near_poverty    boolean,
    requires_basic_pension   boolean,
    requires_disability      boolean,
    requires_veteran         boolean,
    requires_single_household boolean,
    conditions_summary       text,
    field_sources            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    verified_at              timestamptz NOT NULL,
    CONSTRAINT ck_eligibility_age CHECK (min_age IS NULL OR max_age IS NULL OR min_age <= max_age),
    CONSTRAINT ck_eligibility_ltc_grades CHECK (ltc_grades IS NULL OR ltc_grades <@ ARRAY[1, 2, 3, 4, 5, 6]::smallint[])
);

CREATE INDEX ix_eligibility_age ON benefit_eligibility (min_age, max_age);

-- 그룹 병합 후보
CREATE TABLE benefit_group_candidate (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id bigint       NOT NULL REFERENCES benefit (id),
    target_id  bigint       NOT NULL REFERENCES benefit (id),
    method     varchar(20)  NOT NULL,
    score      numeric(4, 3),
    status     varchar(20)  NOT NULL DEFAULT 'PENDING',
    created_at timestamptz  NOT NULL DEFAULT now(),
    decided_at timestamptz,
    CONSTRAINT uk_group_candidate UNIQUE (benefit_id, target_id),
    CONSTRAINT ck_group_candidate_pair CHECK (benefit_id <> target_id),
    CONSTRAINT ck_group_candidate_method CHECK (method IN ('NAME_EXACT', 'NAME_SIMILAR', 'AI')),
    CONSTRAINT ck_group_candidate_status CHECK (status IN ('PENDING', 'MERGED', 'REJECTED'))
);

-- 검토 대기열
CREATE TABLE review_item (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id           bigint      NOT NULL REFERENCES benefit (id),
    raw_id               bigint REFERENCES benefit_raw (id),
    reason               varchar(30) NOT NULL,
    claude_extraction_id bigint REFERENCES ai_extraction (id),
    gpt_extraction_id    bigint REFERENCES ai_extraction (id),
    group_candidate_id   bigint REFERENCES benefit_group_candidate (id),
    detail               jsonb,
    status               varchar(20) NOT NULL DEFAULT 'PENDING',
    resolution_note      text,
    resolved_by          varchar(100),
    resolved_at          timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_review_reason CHECK (reason IN ('MODEL_MISMATCH', 'SCHEMA_INVALID', 'STRUCTURED_MISMATCH',
                                                  'GROUP_CANDIDATE', 'SOURCE_REMOVED', 'OTHER')),
    CONSTRAINT ck_review_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'RESOLVED'))
);

CREATE UNIQUE INDEX uk_review_pending ON review_item (benefit_id, reason) WHERE status = 'PENDING';
CREATE INDEX ix_review_status ON review_item (status, created_at);

-- 수집 실행 이력
CREATE TABLE collect_run (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        varchar(20) NOT NULL,
    status        varchar(20) NOT NULL,
    started_at    timestamptz NOT NULL,
    finished_at   timestamptz,
    api_calls     int         NOT NULL DEFAULT 0,
    items_seen    int         NOT NULL DEFAULT 0,
    items_new     int         NOT NULL DEFAULT 0,
    items_changed int         NOT NULL DEFAULT 0,
    items_removed int         NOT NULL DEFAULT 0,
    error_message text,
    CONSTRAINT ck_collect_run_source CHECK (source IN ('NATIONAL', 'LOCAL', 'GOV24')),
    CONSTRAINT ck_collect_run_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED'))
);

CREATE INDEX ix_collect_run_source ON collect_run (source, started_at DESC);

-- API별 일일 호출 수 (트래픽 한도 관리, public-api.md §8)
CREATE TABLE api_daily_usage (
    source     varchar(20) NOT NULL,
    usage_date date        NOT NULL,
    call_count int         NOT NULL DEFAULT 0,
    PRIMARY KEY (source, usage_date),
    CONSTRAINT ck_api_daily_usage_source CHECK (source IN ('NATIONAL', 'LOCAL', 'GOV24'))
);
